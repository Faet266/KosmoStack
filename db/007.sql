CREATE TABLE rag_source_revisions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_key TEXT NOT NULL,
  snapshot_digest TEXT NOT NULL,
  decision TEXT NOT NULL CHECK (decision IN ('confirm', 'unreadable', 'open')),
  author TEXT NOT NULL,
  reason TEXT NOT NULL,
  source_page INTEGER NOT NULL CHECK (source_page >= 1),
  source_url TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rag_source_revisions_history
  ON rag_source_revisions (snapshot_digest, record_key, id DESC);
