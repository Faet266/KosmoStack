-- Core publications table
    CREATE TABLE IF NOT EXISTS publications (
      id TEXT PRIMARY KEY,
      title TEXT,
      authors TEXT,
      year INTEGER,
      doi TEXT,
      filename TEXT NOT NULL,
      page_count INTEGER NOT NULL DEFAULT 0,
      total_words INTEGER NOT NULL DEFAULT 0,
      word_count_method TEXT,
      extractor_name TEXT,
      extractor_version TEXT,
      processing_status TEXT NOT NULL DEFAULT 'pending'
        CHECK(processing_status IN ('pending','processing','done','error')),
      error_message TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    -- One row per PDF page
    CREATE TABLE IF NOT EXISTS pages (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      publication_id TEXT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
      page_number INTEGER NOT NULL CHECK(page_number >= 1),
      text_content TEXT NOT NULL DEFAULT '',
      word_count INTEGER NOT NULL DEFAULT 0,
      character_count INTEGER NOT NULL DEFAULT 0,
      has_text INTEGER NOT NULL DEFAULT 0,
      extraction_method TEXT NOT NULL DEFAULT 'pdfjs',
      extraction_confidence DOUBLE PRECISION,
      processing_status TEXT NOT NULL DEFAULT 'done',
      error_message TEXT,
      UNIQUE(publication_id, page_number)
    );

    -- Every numeric value found in any page (unfiltered)
    CREATE TABLE IF NOT EXISTS numeric_candidates (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      publication_id TEXT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
      page_number INTEGER NOT NULL,
      raw_value TEXT NOT NULL,
      numeric_value DOUBLE PRECISION,
      unit TEXT,
      context_text TEXT NOT NULL,
      source_fragment TEXT NOT NULL,
      bbox_x0 DOUBLE PRECISION, bbox_y0 DOUBLE PRECISION, bbox_x1 DOUBLE PRECISION, bbox_y1 DOUBLE PRECISION,
      coordinate_system TEXT DEFAULT 'pdf-user-space-points',
      extraction_method TEXT NOT NULL DEFAULT 'pdfjs',
      confidence DOUBLE PRECISION,
      -- classification fields (filled after entity extraction)
      metric_name TEXT,
      metric_variant TEXT,
      metric_k INTEGER,
      metric_group TEXT,
      metric_direction TEXT,
      is_classified INTEGER NOT NULL DEFAULT 0,
      FOREIGN KEY(publication_id, page_number) REFERENCES pages(publication_id, page_number)
    );
    CREATE INDEX IF NOT EXISTS idx_nc_pub ON numeric_candidates(publication_id);
    CREATE INDEX IF NOT EXISTS idx_nc_page ON numeric_candidates(publication_id, page_number);
    CREATE INDEX IF NOT EXISTS idx_nc_classified ON numeric_candidates(publication_id, is_classified);

    -- RAG configurations
    CREATE TABLE IF NOT EXISTS configurations (
      id TEXT PRIMARY KEY,
      publication_id TEXT REFERENCES publications(id) ON DELETE CASCADE,
      name TEXT,
      rag_variant TEXT,
      retrieval_method TEXT,
      retriever_model TEXT,
      embedding_model TEXT,
      embedding_version TEXT,
      chunking_method TEXT,
      chunk_size INTEGER,
      chunk_overlap INTEGER,
      chunk_unit TEXT,
      index_type TEXT,
      vector_store TEXT,
      top_k INTEGER,
      reranker_model TEXT,
      generator_model TEXT,
      generator_version TEXT,
      prompt_strategy TEXT,
      context_strategy TEXT,
      description TEXT,
      version TEXT,
      note TEXT,
      source TEXT DEFAULT 'local'
    );
    CREATE INDEX IF NOT EXISTS idx_cfg_pub ON configurations(publication_id);

    -- Datasets
    CREATE TABLE IF NOT EXISTS datasets (
      id TEXT PRIMARY KEY,
      publication_id TEXT REFERENCES publications(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      description TEXT,
      version TEXT,
      source_url TEXT,
      language TEXT,
      data_split TEXT,
      scientific_domain TEXT,
      note TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_ds_pub ON datasets(publication_id);

    -- Tasks
    CREATE TABLE IF NOT EXISTS tasks (
      id TEXT PRIMARY KEY,
      publication_id TEXT REFERENCES publications(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      task_type TEXT,
      description TEXT,
      note TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_task_pub ON tasks(publication_id);

    -- Experiments (links publication + config + dataset + task)
    CREATE TABLE IF NOT EXISTS experiments (
      id TEXT PRIMARY KEY,
      publication_id TEXT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
      configuration_id TEXT REFERENCES configurations(id),
      dataset_id TEXT REFERENCES datasets(id),
      task_id TEXT REFERENCES tasks(id),
      name TEXT,
      description TEXT,
      evaluation_protocol TEXT,
      baseline_name TEXT,
      hardware TEXT,
      latency_ms DOUBLE PRECISION,
      tokens_per_query INTEGER,
      sample_size INTEGER,
      extra_params TEXT,
      note TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_exp_pub ON experiments(publication_id);

    -- Confirmed metric results (linked to experiments)
    CREATE TABLE IF NOT EXISTS results (
      id TEXT PRIMARY KEY,
      experiment_id TEXT NOT NULL REFERENCES experiments(id) ON DELETE CASCADE,
      publication_id TEXT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
      candidate_id INTEGER REFERENCES numeric_candidates(id),
      metric_name TEXT NOT NULL,
      metric_variant TEXT,
      metric_k INTEGER,
      metric_group TEXT,
      metric_direction TEXT,
      metric_value DOUBLE PRECISION,
      metric_unit TEXT,
      raw_value TEXT,
      raw_unit TEXT,
      normalized_value DOUBLE PRECISION,
      normalized_unit TEXT,
      baseline_value DOUBLE PRECISION,
      aggregation TEXT,
      sample_size INTEGER,
      result_origin TEXT DEFAULT 'primary'
        CHECK(result_origin IN ('primary','cited','unclassified')),
      cited_publication_id TEXT,
      extraction_status TEXT DEFAULT 'extracted'
        CHECK(extraction_status IN ('extracted','present_not_extractable','absent')),
      extraction_method TEXT,
      extractor_version TEXT,
      extraction_confidence DOUBLE PRECISION,
      source_page INTEGER,
      source_section TEXT,
      source_table TEXT,
      source_figure TEXT,
      source_fragment TEXT NOT NULL DEFAULT '',
      source_bbox TEXT,
      source_coordinate_system TEXT,
      duplicate_of TEXT REFERENCES results(id) DEFERRABLE INITIALLY IMMEDIATE,
      review_status TEXT DEFAULT 'unreviewed'
        CHECK(review_status IN ('verified','pending','unreviewed')),
      note TEXT
    );
    CREATE INDEX IF NOT EXISTS idx_res_pub ON results(publication_id);
    CREATE INDEX IF NOT EXISTS idx_res_exp ON results(experiment_id);

    -- Issues / warnings per publication
    CREATE TABLE IF NOT EXISTS issues (
      id TEXT PRIMARY KEY,
      publication_id TEXT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
      page_number INTEGER,
      issue_type TEXT NOT NULL DEFAULT 'extraction_warning',
      check_name TEXT,
      description TEXT NOT NULL,
      severity TEXT NOT NULL DEFAULT 'warning'
        CHECK(severity IN ('error','warning','info')),
      status TEXT NOT NULL DEFAULT 'open'
        CHECK(status IN ('open','resolved','ignored')),
      record_ids TEXT,
      source_fragment TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE INDEX IF NOT EXISTS idx_issues_pub ON issues(publication_id);
