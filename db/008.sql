CREATE TABLE research_articles (
  area TEXT NOT NULL CHECK (area IN ('solar', 'rag', 'space')),
  id TEXT NOT NULL, title TEXT NOT NULL, authors TEXT[] NOT NULL DEFAULT '{}',
  year INTEGER, doi TEXT, source_url TEXT NOT NULL, pdf_url TEXT, provider TEXT NOT NULL,
  pages INTEGER, source_sha256 TEXT,
  PRIMARY KEY (area, id)
);
CREATE TABLE research_fragments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area TEXT NOT NULL, article_id TEXT NOT NULL, location TEXT NOT NULL
    CHECK (location IN ('title', 'abstract', 'keywords', 'page', 'result')),
  page INTEGER, source_url TEXT NOT NULL, body TEXT NOT NULL,
  search_vector TSVECTOR GENERATED ALWAYS AS (to_tsvector('simple', lower(body COLLATE "pg_c_utf8"))) STORED,
  FOREIGN KEY (area, article_id) REFERENCES research_articles(area, id) ON DELETE CASCADE
);
CREATE INDEX research_fragments_article ON research_fragments (area, article_id);
CREATE INDEX research_fragments_search ON research_fragments USING GIN (search_vector);
CREATE TABLE research_tags (
  area TEXT NOT NULL, key TEXT NOT NULL, label TEXT NOT NULL, aliases TEXT[] NOT NULL,
  PRIMARY KEY (area, key)
);
CREATE TABLE research_tag_matches (
  area TEXT NOT NULL, tag TEXT NOT NULL, article_id TEXT NOT NULL, fragment_id BIGINT NOT NULL,
  alias TEXT NOT NULL, excerpt TEXT NOT NULL,
  PRIMARY KEY (area, tag, article_id, fragment_id),
  FOREIGN KEY (area, tag) REFERENCES research_tags (area, key) ON DELETE CASCADE,
  FOREIGN KEY (area, article_id) REFERENCES research_articles (area, id) ON DELETE CASCADE,
  FOREIGN KEY (fragment_id) REFERENCES research_fragments ON DELETE CASCADE
);
CREATE INDEX research_matches_article ON research_tag_matches (area, article_id, tag);
